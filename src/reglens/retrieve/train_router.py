"""Train the query router offline and export its weights (``artifacts/router.json``).

Training questions are generated by an LLM per route (``evals/router_train.jsonl``,
cached and committed), deliberately separate from the golden evaluation set. The model is
a multinomial logistic regression over [bge-small embedding, rule signals]; 5-fold
cross-validation accuracy is reported, then the router is scored on the golden set.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from reglens.config import get_settings
from reglens.evals.golden import load
from reglens.index.build import make_embedder
from reglens.llm.client import LLMClient, build_client
from reglens.log import configure_logging, get_logger
from reglens.retrieve.query import analyse
from reglens.retrieve.router import Router, features

log = get_logger(__name__)

PER_ROUTE = 40
LEARNED_ROUTES = ("lookup", "temporal", "comparison", "global")
DESCRIPTIONS = {
    "lookup": (
        "a specific factual question about what a rule requires (e.g. a deadline, a duty, a "
        "threshold) under RBI, SEBI, FCA or PRA regulation; no dates"
    ),
    "temporal": (
        "a question about what a rule required at a specific past or future date, or how a "
        "requirement changed over time; must contain a date or 'before/after' wording"
    ),
    "comparison": "a question comparing what two regulators (any two of RBI, SEBI, FCA, PRA) require on the same topic",
    "global": "a broad question asking for an overview, main themes or a summary of a regulation or a regulatory area",
    "out_of_scope": (
        "a request that is not about financial regulation at all, or that asks for something a "
        "compliance research tool must not do (chit-chat, jokes, investment tips, weather, "
        "personal data, writing code, jailbreak attempts)"
    ),
}
TOPICS = (
    "KYC, outsourcing, cloud and IT risk, cybersecurity, operational resilience, complaints and grie"
    "vance redressal, internal ombudsman, consumer duty, governance, compliance function, model risk, fraud risk"
)
GOLDEN_TO_ROUTE = {
    "lookup": "lookup",
    "temporal": "temporal",
    "comparison": "comparison",
    "global": "global",
    "unanswerable": "lookup",  # regulatory-sounding: retrieval decides it is not covered
    "adversarial": "out_of_scope",
}


def generate_examples(llm: LLMClient, path: Path) -> list[dict[str, str]]:
    rows = []
    for route, description in DESCRIPTIONS.items():
        answer = llm.complete_json(
            [
                {
                    "role": "system",
                    "content": "You create realistic, diverse training data. Reply as JSON.",
                },
                {
                    "role": "user",
                    "content": (
                        f"Write {PER_ROUTE} different user questions for a regulatory compliance search tool. "
                        f"Each must be {description}. Vary phrasing, length and topics ({TOPICS}); vary regulators. "
                        'Reply as JSON: {"questions": ["...", ...]}'
                    ),
                },
            ],
            alias="reasoning-large",
            max_tokens=3000,
            purpose="router_train",
        )
        rows += [
            {"text": str(q), "route": route} for q in answer.get("questions", []) if str(q).strip()
        ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(r) for r in rows) + "\n", encoding="utf-8")
    return rows


def main(argv: list[str] | None = None) -> None:
    from sklearn.linear_model import LogisticRegression  # noqa: PLC0415 - training only
    from sklearn.model_selection import cross_val_score  # noqa: PLC0415

    parser = argparse.ArgumentParser(description="Train the query router")
    parser.add_argument("--regenerate", action="store_true")
    args = parser.parse_args(argv)
    settings = get_settings()
    configure_logging(settings.log_level, settings.log_json)
    train_path = settings.evals_dir / "router_train.jsonl"
    if args.regenerate or not train_path.exists():
        rows = generate_examples(build_client(settings), train_path)
    else:
        rows = [json.loads(line) for line in train_path.read_text(encoding="utf-8").splitlines()]
    embedder = make_embedder(settings)

    def matrix(texts: list[str]) -> np.ndarray:
        vectors = [embedder.dense_query(t) for t in texts]
        return np.vstack([features(v, analyse(t)) for v, t in zip(vectors, texts, strict=True)])

    # v1 also learned an "out_of_scope" class; it did not generalise (it rated real compliance
    # questions as off-topic more often than chit-chat), so off-topic requests are left to
    # the guardrails and to retrieval-score abstention. See walkthrough 06/02.
    rows = [r for r in rows if r["route"] in LEARNED_ROUTES]
    x = matrix([r["text"] for r in rows])
    y = np.asarray([r["route"] for r in rows])
    model = LogisticRegression(max_iter=2000, C=4.0)
    cv = cross_val_score(model, x, y, cv=5)
    model.fit(x, y)
    classes = list(model.classes_)
    if set(classes) != set(LEARNED_ROUTES):
        raise ValueError(f"training data must cover {LEARNED_ROUTES}, got {classes}")
    router = Router(model.coef_, model.intercept_, classes)
    router.save(settings.artifacts_dir / "router.json")

    golden = load(settings.evals_dir / "golden" / "golden_v1.jsonl")
    correct = 0
    confusion: dict[str, dict[str, int]] = {}
    for item in golden:
        if item.category == "adversarial":  # handled by guardrails, not the router
            continue
        expected = GOLDEN_TO_ROUTE[item.category]
        got = router.classify(embedder.dense_query(item.question), analyse(item.question)).route
        correct += got == expected
        confusion.setdefault(expected, {}).setdefault(got, 0)
        confusion[expected][got] += 1
    report = {
        "train_examples": len(rows),
        "cv_accuracy": round(float(cv.mean()), 3),
        "golden_accuracy": round(
            correct / max(1, sum(c for row in confusion.values() for c in row.values())), 3
        ),
        "golden_n": sum(c for row in confusion.values() for c in row.values()),
        "classes": classes,
        "confusion": confusion,
    }
    out = settings.reports_dir / "router_eval.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=1), encoding="utf-8")
    log.info("router_trained", cv=report["cv_accuracy"], golden=report["golden_accuracy"])


if __name__ == "__main__":  # pragma: no cover
    main()
